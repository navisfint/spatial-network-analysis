def nqp_long_names() -> list[str]:
    """新质生产力 30 个指标的唯一标识名（同名三级指标加序号后缀）。

    因为原文里"新型生产工具""数字基础设施"等三级指标名下挂了多个代理变量，
    直接拿三级指标名做键会重名，这里生成 三级指标_含义 的唯一名。
    """
    return [f"{t[0]}|{t[1]}" for t in NQP_SYSTEM]


def nqp_meta() -> "dict[str, dict]":
    """返回 {唯一指标名: {二级, 一级, 权重, 含义, 三级}}"""
    return {
        f"{t[0]}|{t[1]}": {
            "三级": t[0], "含义": t[1], "权重": t[2], "二级": t[3], "一级": t[4],
        }
        for t in NQP_SYSTEM
    }


def nqp_parent_weights() -> dict:
    """按二级/一级归集权重（用于复原论文 59.04% / 40.96% 的核对）。"""
    out = {"一级": {}, "二级": {}}
    for t in NQP_SYSTEM:
        out["一级"][t[4]] = out["一级"].get(t[4], 0.0) + t[2]
        out["二级"][t[3]] = out["二级"].get(t[3], 0.0) + t[2]
    return out


def cp_meta() -> "dict[str, dict]":
    """返回 {指标名: {单位, 性质, 二级, 一级}}"""
    return {
        t[0]: {"单位": t[1], "性质": t[2], "二级": t[3], "一级": t[4]}
        for t in CP_SYSTEM
    }


